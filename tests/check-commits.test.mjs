import { test } from "node:test";
import assert from "node:assert/strict";
import { checkMessage, checkDiff, checkRange } from "../tools/check-commits.mjs";

const rules = f => f.map(x => `${x.level}:${x.rule}`);
const CONF = { TITLE_PREFIXES: "FOO COMMON", SUBPREFIXES: "AA BB", INDENT: "tabs", POINTER_STYLE: "right", BRACES: "same-line",
  KEYWORD_SPACE: "yes", NEW_FILE_HEADER: "GNU General Public License", ERROR_PATTERNS: "\\bstd::|\\bthrow\\b|\\btry\\b", WARN_PATTERNS: "\\bfloat\\b", SCOPE: "engines/foo" };

test("good message passes", () => {
  assert.deepEqual(checkMessage("FOO: AA: Fix scroll step count\n\nThe original divides once.\n", CONF), []);
});
test("DRAFT is an error unless allowed", () => {
  assert.ok(rules(checkMessage("DRAFT FOO: Fix x", CONF)).includes("error:R2"));
  assert.ok(!rules(checkMessage("DRAFT FOO: Fix x", CONF, { allowDraft: true })).includes("error:R2"));
});
test("co-author trailers are errors, AI credits warnings, product names fine", () => {
  assert.ok(rules(checkMessage("FOO: Fix x\n\nCo-Authored-By: Someone <a@b>", CONF)).includes("error:R3"));
  assert.ok(rules(checkMessage("FOO: Fix x\n\nGenerated with Claude", CONF)).includes("warn:R3"));
  assert.deepEqual(checkMessage("FOO: Fix crash in Gemini Rue intro", CONF), []);
  assert.deepEqual(checkMessage("FOO: Fix x\n\nGenerated by the script compiler.", CONF), []);
});
test("title prefix, tense, length, blank line", () => {
  assert.ok(rules(checkMessage("Fix something", CONF)).includes("error:R8"));
  assert.ok(rules(checkMessage("BAR: Fix something", CONF)).includes("error:R8"));
  assert.ok(rules(checkMessage("FOO: CC: Fix something", CONF)).includes("warn:R8"));
  assert.ok(rules(checkMessage("FOO: Fixed something", CONF)).includes("warn:R8"));
  assert.ok(rules(checkMessage("FOO: Fixes something", CONF)).includes("warn:R8"));
  assert.ok(rules(checkMessage("FOO: " + "x".repeat(50), CONF)).includes("warn:R8"));
  assert.ok(rules(checkMessage("FOO: " + "x".repeat(70), CONF)).includes("error:R8"));
  assert.ok(rules(checkMessage("FOO: Fix\nbody without blank line", CONF)).includes("error:R8"));
  assert.deepEqual(checkMessage("COMMON: Fix x", CONF), []);
});
test("no prefixes configured: any title format", () => {
  assert.deepEqual(checkMessage("Fix the thing"), []);
});

const diff = (lines, file = "engines/foo/a.cpp") => `diff --git a/${file} b/${file}\n--- a/${file}\n+++ b/${file}\n@@ -1,0 +1,${lines.length} @@\n${lines.map(l => "+" + l).join("\n")}\n`;
test("diff: clean code passes", () => {
  assert.deepEqual(checkDiff(diff(["\tif (a) {", "\t\tFoo *p = b();", "\t}"]), CONF), []);
});
test("diff: spaces, trailing, forbidden, discouraged, if(", () => {
  const r = rules(checkDiff(diff(["    x();", "\tx(); ", "\tstd::vector<int> v;", "\tfloat f;", "\tif(a) b();"]), CONF));
  for (const e of ["error:R6", "error:R7", "warn:R7"]) assert.ok(r.includes(e), e);
});
test("diff: no false positives in strings and comments", () => {
  const r = checkDiff(diff(["\twarning(\"Cannot load, try again\");", "\t/* we try the next slot", "\t * if(x) std::vector */", "\t*dst++ = c;", "\t*dst++ = c;", "\t*dst++ = c;", "\t*dst++ = c;"]), CONF);
  assert.deepEqual(r, []);
});
test("diff: long comment block", () => {
  assert.ok(rules(checkDiff(diff(["\t// a", "\t// b", "\t// c", "\t// d"]), CONF)).includes("warn:R4"));
});
test("diff: pointer style", () => {
  assert.ok(rules(checkDiff(diff(["\tFoo* p = b();"]), CONF)).includes("warn:R6"));
});
test("diff: file outside the scope", () => {
  assert.ok(rules(checkDiff(diff(["\tx();"], "common/a.cpp"), CONF)).includes("warn:R13"));
});
test("new source file needs the license header (R25)", () => {
  const d = `diff --git a/engines/foo/b.cpp b/engines/foo/b.cpp\nnew file mode 100644\n--- /dev/null\n+++ b/engines/foo/b.cpp\n@@ -0,0 +1,1 @@\n+int x;\n`;
  assert.ok(rules(checkDiff(d, CONF)).includes("error:R25"));
  const ok = d.replace("+int x;", "+ * it under the terms of the GNU General Public License as published by");
  assert.ok(!rules(checkDiff(ok, CONF)).includes("error:R25"));
});
test("range cannot be an option (injection)", () => {
  assert.throws(() => checkRange({ repo: ".", range: "--output=/tmp/x" }), /invalid range/);
});
